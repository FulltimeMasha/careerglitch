#!/usr/bin/env node
// scripts/gen_minidata.mjs — regenerate api/_lib/minidata.mjs from the
// gate's own data (index.html inline PROFS/COFACTS/SEATS/GRIDS + v11.js
// V11/GV11/QUOTES), so the mini-report emails can never drift from the
// verdicts and digits the gate shows. Run after any gate data change:
//   node scripts/gen_minidata.mjs
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

function makeStub() {
  const fn = function () { return stub; };
  const stub = new Proxy(fn, {
    get(t, p) {
      if (p === Symbol.toPrimitive) return () => '';
      if (p === 'length') return 0;
      return stub;
    },
    set() { return true; },
    apply() { return stub; },
  });
  return stub;
}
const el = makeStub();
const dclHandlers = [];
const documentStub = {
  readyState: 'loading',
  getElementById: () => el,
  querySelectorAll: () => [],
  querySelector: () => el,
  createElement: () => el,
  addEventListener: (ev, fn) => { if (ev === 'DOMContentLoaded') dclHandlers.push(fn); },
  body: el, head: el,
};
const sandbox = {
  document: documentStub,
  navigator: { userAgent: 'gen-minidata' },
  location: { origin: 'https://careerglitch.com', search: '', href: 'https://careerglitch.com/' },
  localStorage: { getItem: () => null, setItem() {}, removeItem() {} },
  Event: class { constructor(type) { this.type = type; } },
  MutationObserver: class { observe() {} disconnect() {} },
  URLSearchParams,
  setInterval: () => 0, setTimeout: () => 0, clearInterval() {}, clearTimeout() {},
  console,
};
sandbox.window = {
  matchMedia: () => ({ matches: true }),
  addEventListener() {},
  scrollTo() {},
  location: sandbox.location,
  MutationObserver: sandbox.MutationObserver,
};
sandbox.globalThis = sandbox;
vm.createContext(sandbox);

vm.runInContext(fs.readFileSync(path.join(SITE, 'v11.js'), 'utf8'), sandbox, { filename: 'v11.js' });
// Creator Staff Reframe block: split out of v11.js into /cst.js on 2026-11-01
// (upload cap) and loaded there via document.write; evaluate it here directly.
vm.runInContext(fs.readFileSync(path.join(SITE, 'cst.js'), 'utf8'), sandbox, { filename: 'cst.js' });
// Expansion wave 2 (2026-11-01): gate data for the new professions
// lives in /profs2.js (loaded by v11.js via document.write); evaluate
// it here directly, after cst.js, matching the page's load order.
vm.runInContext(fs.readFileSync(path.join(SITE, 'profs2.js'), 'utf8'), sandbox, { filename: 'profs2.js' });
// Expansion wave 3 (truck driver, …) lives in /profs3.js (loaded by
// v11.js via document.write, after profs2.js); evaluate it here too.
vm.runInContext(fs.readFileSync(path.join(SITE, 'profs3.js'), 'utf8'), sandbox, { filename: 'profs3.js' });
// Expansion wave 4 (AI product manager) lives in /profs4.js (loaded by
// v11.js via document.write, after profs3.js); evaluate it here too.
vm.runInContext(fs.readFileSync(path.join(SITE, 'profs4.js'), 'utf8'), sandbox, { filename: 'profs4.js' });
const html = fs.readFileSync(path.join(SITE, 'index.html'), 'utf8');
const start = html.indexOf('<script>\n', html.indexOf('share.js'));
const end = html.indexOf('</script>', start);
if (start < 0 || end < 0) { console.error('inline gate script not found'); process.exit(1); }
vm.runInContext(html.slice(start + '<script>\n'.length, end), sandbox, { filename: 'index-inline.js' });
for (const fn of dclHandlers) fn(); // analyst extension injects here

const names = ['PROFS', 'COFACTS', 'SEATS', 'GRIDS', 'V11', 'GV11', 'QUOTES'];
const out = ['// api/_lib/minidata.mjs — GENERATED by scripts/gen_minidata.mjs from the',
  '// gate data in index.html + v11.js (same verdicts, same digits). Do not',
  '// hand-edit; change the gate data and re-run the generator.', ''];
const vals = {};
for (const name of names) {
  const val = vm.runInContext(`typeof ${name} !== 'undefined' ? ${name} : undefined`, sandbox);
  if (val === undefined) { console.error('MISSING global', name); process.exit(1); }
  vals[name] = val;
}
/* Hoist long strings that repeat across the data (each profession's
   NEXT pitch is serialized once per seat) into shared consts. Added
   2026-11-01: the plain-language texts pushed the file past the
   ~98KB Vercel upload-argument cap. Exported VALUES are unchanged -
   the consts hold the exact same strings. */
/* Split 2026-11-01 (expansion wave 2): the single generated module
   outgrew the ~98KB upload cap again at 49 seats, so the exports are
   written to THREE modules - minidata.mjs (PROFS/COFACTS/GRIDS/
   GV11/QUOTES), minidata-seats.mjs (SEATS), minidata-v11.mjs (V11).
   Hoisting runs per file; values are identical to the single-file
   era. Consumers import from the file that owns the export. */
const FILES = [
  { dest: 'api/_lib/minidata.mjs', names: ['PROFS', 'COFACTS', 'GRIDS', 'GV11', 'QUOTES'] },
  { dest: 'api/_lib/minidata-seats.mjs', names: ['SEATS'] },
  { dest: 'api/_lib/minidata-v11.mjs', names: ['V11'] },
];
for (const part of FILES) {
  const lines = out.slice();
  const strCount = new Map();
  (function walk(v){
    if (typeof v === 'string') { if (v.length >= 300) strCount.set(v, (strCount.get(v) || 0) + 1); }
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  })(part.names.map((n) => vals[n]));
  const hoisted = [...strCount.entries()].filter(([, c]) => c >= 3)
    .sort((a, b) => b[0].length * b[1] - a[0].length * a[1]);
  const hoistId = new Map(hoisted.map(([str], i) => [str, '_H' + (i + 1)]));
  for (const [str, id] of hoistId) lines.push(`const ${id} = ${JSON.stringify(str)};`);
  if (hoisted.length) lines.push('');
  for (const name of part.names) {
    let json = JSON.stringify(vals[name]);
    for (const [str, id] of hoistId) json = json.split(JSON.stringify(str)).join(id);
    lines.push(`export const ${name} = ${json};`, '');
  }
  const dest = path.join(SITE, part.dest);
  fs.writeFileSync(dest, lines.join('\n'));
  console.log(`wrote ${dest} (${fs.statSync(dest).size} bytes)`);
}
const seats = Object.keys(JSON.parse(JSON.stringify(vm.runInContext('SEATS', sandbox)))).length;
console.log(`seats: ${seats}`);
